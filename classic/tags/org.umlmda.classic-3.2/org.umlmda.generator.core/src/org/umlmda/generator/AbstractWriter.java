package org.umlmda.generator;

import java.util.Iterator;
import java.util.Properties;

import org.umlmda.generator.model.uml.GeneratorModelElement;
import org.umlmda.generator.model.util.Feedback;
import org.umlmda.generator.model.util.GeneratorRuntime;
import org.umlmda.generator.profile.Artefact;
import org.umlmda.generator.profile.Property;



/**
 * Abstract baseclass for all writers generated by jostraca. With the interface of this class the
 * generator controller can call the writers to do the specific generation.
 * @author Dieter Moroff
 */
public abstract class AbstractWriter {
   static public final int OPTIONAL  = 1;
   static public final int COMMON    = 2;
   static public final int MANDATORY = 3;

   private GeneratorRuntime runtime;
   private Generator generator;
   private String userSectionPrefix;
   private String baseName;
   private int userSectionLevel = COMMON;
   private String lineComment = "//";
   protected GeneratorRuntimeConfig config;
   private Properties properties;
   
   /**
    * Modelelement, for which the generator was invoked
    */
   private Object modelElement = null;


   /**
    * Method is generated by Jostraca and called in the run method, it shouldn't be called from
    * anywhere else.
    */
   protected abstract void writer__initialize();

   /**
    * Method is generated by Jostraca and called in the run method, it shouldn't be called from
    * anywhere else.
    */
   protected abstract void writer__write() throws Exception;

   /**
    * Returns the feedback.
    * @return GeneratorFeedback
    */
   public Feedback getFeedback()
   {
      return runtime.getFeedback();
   }

   /**
    * Method to be called in templates, to start a mandatory user section
    * @param id name of the userSection
    * @return String
    */
   protected String beginUserSection(String id) {
      return beginUserSection(id, MANDATORY);
   }

   /**
    * Method beginUserSection.
    * @param id
    * @param optional
    * @return String
    */
   protected String beginUserSection(String id, int optional) {
      if(optional > userSectionLevel)
         return "";
         
      StringBuffer sb = new StringBuffer(50);
      sb.append(lineComment);
      sb.append(config.getEyecatcherPrefix());
      sb.append(config.getBeginEyecatcher());
      sb.append(" ");
      sb.append(userSectionPrefix);
      sb.append(".");
      sb.append(id);
      return sb.toString();
   }

   /**
    * Method endUserSection.
    * @param id
    * @return String
    */
   protected String endUserSection(String id) {
      return endUserSection(id, MANDATORY);
   }
   
   /**
    * Method endUserSection.
    * @param id
    * @param optional
    * @return String
    */
   protected String endUserSection(String id, int optional) {
      if(optional > userSectionLevel)
         return "";
         
      StringBuffer sb = new StringBuffer(50);
      sb.append(lineComment);
      sb.append(config.getEyecatcherPrefix());
      sb.append(config.getEndEyecatcher());
      sb.append(" ");
      sb.append(userSectionPrefix);
      sb.append(".");
      sb.append(id);
      return sb.toString();
      
   }
   
   /**
    * @return
    */
   public int getUserSectionLevel() {
      return userSectionLevel;
   }

   /**
    * @param i
    */
   public void setUserSectionLevel(int i) {
      userSectionLevel = i;
   }

   /**
    * @return
    */
   public String getLineComment() {
      return lineComment;
   }

   /**
    * @param string
    */
   public void setLineComment(String string) {
      lineComment = string;
   }

   /**
    * @return
    */
   public String getUserSectionPrefix() {
      return userSectionPrefix;
   }

   /**
    * @param string
    */
   public void setUserSectionPrefix(String string) {
      userSectionPrefix = string;
   }

   /**
    * @return
    */
   public GeneratorRuntimeConfig getConfig() {
      return config;
   }

   /**
    * @param config
    */
   public void setConfig(GeneratorRuntimeConfig config) {
      this.config = config;
   }

   /**
       * @return
       */
   public Object getModelElement() {
      return modelElement;
   }

   /**
       * @param element
       */
   public void setModelElement(Object element) {
      modelElement = element;
   }

   /**
    * @return
    */
   public Generator getGenerator() {
      return generator;
   }

   /**
    * @param generator
    */
   public void setGenerator(Generator generator) {
      this.generator = generator;
      this.runtime = generator.getRuntime();
   }

   /**
    * Callback to control whether the writer will produce any output. Overwriting
    * this method will enable the writer to decide in respect of the current
    * model element to produce output or not.
    */
   public boolean generateOutput() {
      return true;
   }

   /**
    * @param generatorModelElement TODO
    * 
    */
   public static Properties getArtefactProperties(GeneratorModelElement generatorModelElement) {
      Properties properties = new Properties();
   
      Artefact artefact = generatorModelElement.getGeneratorModel().getArtefact();
      for (Iterator ip = artefact.getDefaultProperties().iterator(); ip.hasNext();) {
         Property property = (Property) ip.next();
         
         properties.put(property.getName(), property.getValue());
      }
      return properties;
   }

   /**
    * @return Returns the properties.
    */
   public Properties getProperties() {
      if ( properties == null && getModelElement() instanceof GeneratorModelElement ) {
         properties = getArtefactProperties((GeneratorModelElement) getModelElement());
      }
      else {
         properties = new Properties();
      }
      return properties;
   }
}
